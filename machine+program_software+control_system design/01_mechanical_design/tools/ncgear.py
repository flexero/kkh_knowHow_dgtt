# ---------------------------------------------------------------- chapter 2: pitch curves, closure, conjugate
def r1_fun(P, A=None):
    """Pitch radius of gear 1 as a function of its polar angle theta (body frame); A = size parameter."""
    t, e = P["type"], P["e"]
    if t == "ellipse":
        A = A or 60.0
        return lambda th: A * (1 - e * e) / (1 - e * math.cos(th))
    if t == "nlobe":
        A = A or 50.0
        n = P["n1"]
        return lambda th: A * (1 - e * e) / (1 - e * math.cos(n * th))
    raise ValueError("r1_fun: function type uses fdash()")

def fdash(P):
    """Function type: wanted d(phi2)/d(phi1) as a Fourier series (mean 1 -> gear 2 turns once per turn of gear 1)."""
    F = P["fourier"]
    return lambda ph: 1 + sum(a * math.cos(k * ph) + b * math.sin(k * ph) for k, a, b in F)

def integrate(f, a, b, n=2000):
    """Simpson rule."""
    n += n % 2
    h = (b - a) / n
    s = f(a) + f(b) + sum((4 if i % 2 else 2) * f(a + i * h) for i in range(1, n))
    return s * h / 3

def centre_distance(r1, ratio_rev, n=2000):
    """Closure: phi2(2 pi) = int_0^2pi r1 / (a - r1) dphi1 = 2 pi ratio_rev; solved for a by bisection."""
    rmax = max(r1(2 * math.pi * i / 720) for i in range(720))
    lo, hi = rmax * (1 + 1e-9), rmax * 50
    g = lambda a: integrate(lambda t: r1(t) / (a - r1(t)), 0, 2 * math.pi, n) - 2 * math.pi * ratio_rev
    for _ in range(100):
        mid = 0.5 * (lo + hi)
        if g(mid) > 0:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)

def pitch_pair(P, A=None, N=720):
    """Both pitch curves as tables over phi1 (gear 1 angle = body angle at the contact point):
    r1, r2 = a - r1, phi2 = int r1/r2 dphi1, gear-2 body angle theta2 = pi - phi2, arc lengths s1, s2."""
    if P["type"] == "function":
        a = A or 120.0
        fd = fdash(P)
        r1 = lambda th: a * fd(th) / (1 + fd(th))
        ratio = 1.0
    else:
        r1 = r1_fun(P, A)
        ratio = P["n1"] / P["n2"] if P["type"] == "nlobe" else 1.0
        a = centre_distance(r1, ratio)
    ph = [2 * math.pi * i / N for i in range(N + 1)]
    R1 = [r1(p) for p in ph]
    R2 = [a - r for r in R1]
    f = [r / (a - r) for r in R1]
    phi2 = [0.0]
    for i in range(N):                              # trapezoid on a fine table (Simpson-quality with N 720)
        h = ph[i + 1] - ph[i]
        mid = r1(ph[i] + h / 2) / (a - r1(ph[i] + h / 2))
        phi2.append(phi2[-1] + h / 6 * (f[i] + 4 * mid + f[i + 1]))
    th2 = [math.pi - p for p in phi2]
    C1 = [(r * math.cos(t), r * math.sin(t)) for r, t in zip(R1, ph)]
    C2 = [(r * math.cos(t), r * math.sin(t)) for r, t in zip(R2, th2)]
    s1, s2 = [0.0], [0.0]
    for i in range(N):
        s1.append(s1[-1] + math.dist(C1[i], C1[i + 1]))
        s2.append(s2[-1] + math.dist(C2[i], C2[i + 1]))
    # complete pitch curve of gear 2: gear 1 must turn 1 / ratio revolutions until gear 2 has turned once
    rev1 = 1.0 / ratio
    if abs(rev1 - 1) < 1e-12:
        C2f, s2f = C2, s2
    else:
        Nf = int(round(N * rev1))
        C2f, s2f, q = [], [0.0], 0.0
        h = 2 * math.pi * rev1 / Nf
        for i in range(Nf + 1):
            t = i * h
            if i:
                tm = t - h / 2
                q += h / 6 * (r1(t - h) / (a - r1(t - h)) + 4 * r1(tm) / (a - r1(tm)) + r1(t) / (a - r1(t)))
            rr = a - r1(t)
            C2f.append((rr * math.cos(math.pi - q), rr * math.sin(math.pi - q)))
            if i:
                s2f.append(s2f[-1] + math.dist(C2f[-2], C2f[-1]))
    return {"a": a, "r1f": r1, "phi1": ph, "r1": R1, "r2": R2, "phi2": phi2, "theta2": th2, "C1": C1, "C2": C2,
            "s1": s1, "s2": s2, "L1": s1[-1], "L2": s2[-1], "ratio_rev": ratio, "rev1": rev1, "C2full": C2f, "s2full": s2f,
            "L2full": s2f[-1]}

def size_for_module(P):
    """Scale the pitch curve so that its perimeter is exactly z1 pi m (whole number of teeth for the standard tool)."""
    target = P["z1"] * math.pi * P["m"]
    base = 60.0 if P["type"] != "function" else 120.0
    L = pitch_pair(P, base)["L1"]
    A = base * target / L
    for _ in range(3):                              # the perimeter is proportional to the size; refine once for rounding
        L = pitch_pair(P, A)["L1"]
        A *= target / L
    return A

# ---------------------------------------------------------------- chapter 3: curvature, pressure angle, transmission
def polar_props(r, th, h=1e-4):
    """r', r'', curvature k = (r^2 + 2 r'^2 - r r'') / (r^2 + r'^2)^1.5, angle between radius and tangent mu
    (tan mu = r / r'), deviation delta = 90 deg - mu."""
    rp = (r(th + h) - r(th - h)) / (2 * h)
    rpp = (r(th + h) - 2 * r(th) + r(th - h)) / h ** 2
    R = r(th)
    k = (R * R + 2 * rp * rp - R * rpp) / (R * R + rp * rp) ** 1.5
    return {"r": R, "rp": rp, "rpp": rpp, "kappa": k, "rho": 1 / k if k else float("inf"), "delta": math.degrees(math.atan2(rp, R))}

def analyse(P, A=None):
    """Transmission function, curvature and pressure-angle deviation of both gears, equivalent tooth numbers."""
    A = A or size_for_module(P)
    pp = pitch_pair(P, A)
    a = pp["a"]
    r1 = pp["r1f"]
    r2 = lambda t: a - r1(t)
    rows = []
    N = len(pp["phi1"]) - 1
    for i in range(0, N + 1, 4):
        t = pp["phi1"][i]
        g1 = polar_props(r1, t)
        # gear 2 curvature: polar curve r2(theta2) with dtheta2 = -dphi1 r1/r2 -> use the point table numerically
        rows.append({"phi1": t, "phi2": pp["phi2"][i], "r1": pp["r1"][i], "r2": pp["r2"][i], "i": pp["r2"][i] / pp["r1"][i],
                     "kappa1": g1["kappa"], "delta": g1["delta"]})
    # gear-2 curvature from the point table (three-point circle)
    C2 = pp["C2"]
    k2 = []
    for i in range(0, N, 4):
        p0, p1, p2 = C2[(i - 4) % N], C2[i], C2[(i + 4) % N]
        ax, ay, bx, by = p1[0] - p0[0], p1[1] - p0[1], p2[0] - p0[0], p2[1] - p0[1]
        cross = ax * by - ay * bx
        k2.append(2 * cross / (math.dist(p0, p1) * math.dist(p1, p2) * math.dist(p0, p2)))
    m = P["m"]
    rho1 = [1 / r["kappa1"] if r["kappa1"] > 0 else float("inf") for r in rows]
    rho2 = [1 / abs(k) if k else float("inf") for k in k2]
    ok_convex1 = all(r["kappa1"] > 0 for r in rows)
    ok_convex2 = all(k * k2[0] > 0 for k in k2)
    zv_min = 2 * min(min(rho1), min(rho2)) / m
    zmin = 2 / math.sin(math.radians(P["alpha"])) ** 2
    iv = [r["i"] for r in rows]
    return {"A": A, "pp": pp, "rows": rows, "a": a, "i_min": min(iv), "i_max": max(iv), "delta_max": max(abs(r["delta"]) for r in rows),
            "rho1_min": min(rho1), "rho2_min": min(rho2), "convex1": ok_convex1, "convex2": ok_convex2, "zv_min": zv_min, "z_undercut": zmin,
            "z2": P["z1"] * pp["L2full"] / pp["L1"]}

# ---------------------------------------------------------------- chapter 4: tooth generation by rack simulation
def generate_teeth(P, C, s, phase, n_rays=None, steps=None):
    """Envelope of a straight-sided rack cutter (cutter addendum 1.25 m, pressure angle alpha) rolling without slip on
    the pitch curve C (point table with arc length s). Cutter teeth at u = (k + phase) p. For each polar ray of the
    gear body the outline radius is the first radius at which the ray enters any cutter position; the tip is the pitch
    curve offset by +m. Returns the outline [(theta, R)] (star-shaped about the gear centre)."""
    m, al = P["m"], math.radians(P["alpha"])
    p = math.pi * m
    n_rays = n_rays or P["n_rays"]
    steps = steps or P["steps_per_tooth"]
    L = s[-1]
    N = len(C) - 1
    # rack positions: point, unit tangent, outward normal, rack coordinate u0 = s
    pos = []
    npos = int(round(L / p * steps))
    j = 0
    for q in range(npos):
        sq = L * q / npos
        while s[j + 1] < sq:
            j += 1
        f = (sq - s[j]) / (s[j + 1] - s[j])
        X = (C[j][0] + f * (C[j + 1][0] - C[j][0]), C[j][1] + f * (C[j + 1][1] - C[j][1]))
        dx, dy = C[j + 1][0] - C[j][0], C[j + 1][1] - C[j][1]
        d = math.hypot(dx, dy)
        t = (dx / d, dy / d)
        n = (t[1], -t[0]) if (t[1] * X[0] - t[0] * X[1]) > 0 else (-t[1], t[0])     # outward = away from the centre
        pos.append((sq, X, t, n, math.atan2(X[1], X[0])))
    # pitch radius and tip radius along each ray (tip = offset of the pitch curve by +m measured along the normal)
    ang = [math.atan2(c[1], c[0]) for c in C[:-1]]
    out = []
    ta = math.tan(al)
    win = 3.0 * m
    for kr in range(n_rays):
        th = -math.pi + 2 * math.pi * kr / n_rays
        dvec = (math.cos(th), math.sin(th))
        # pitch radius on this ray: nearest table point by angle, then the local deviation for the tip
        best = min(range(N), key=lambda i: abs(math.remainder(ang[i] - th, 2 * math.pi)))
        rp = math.hypot(*C[best])
        R = float("inf")
        for sq, X, t, n, ax in pos:
            if abs(math.remainder(ax - th, 2 * math.pi)) * rp > win:
                continue
            dn, dt = dvec[0] * n[0] + dvec[1] * n[1], dvec[0] * t[0] + dvec[1] * t[1]
            Xn, Xt = X[0] * n[0] + X[1] * n[1], X[0] * t[0] + X[1] * t[1]
            # along the ray: v(rho) = rho dn - Xn, u(rho) = sq + rho dt - Xt
            if dn <= 1e-9:
                continue
            rho_tip = (Xn + 1.0 * m) / dn                     # gear tip (addendum curve) on this ray
            R = min(R, rho_tip)
            rho_v = (Xn - 1.25 * m) / dn                      # v >= -1.25 m (cutter tip line)
            u0 = sq - Xt
            for k in (round((u0 + rp * dt) / p - phase) + dk for dk in (-1, 0, 1)):
                c = (k + phase) * p
                # |u - c| <= p/4 + v tan(al):  u - c <= p/4 + v ta  and  c - u <= p/4 + v ta  (both linear in rho)
                lo = rho_v
                hi = float("inf")
                for sgn in (1, -1):
                    A_ = sgn * dt - ta * dn                    # coefficient of rho in  sgn (u - c) - v ta - p/4 <= 0
                    B_ = sgn * (u0 - c) + ta * Xn - p / 4
                    if abs(A_) < 1e-12:
                        if B_ > 0:
                            lo = float("inf")
                    elif A_ > 0:
                        hi = min(hi, -B_ / A_)
                    else:
                        lo = max(lo, -B_ / A_)
                if lo <= hi and lo < R:
                    R = max(lo, 0.0)
        out.append((th, R))
    return out

def gear_outlines(P, an=None):
    """Tooth outlines of gear 1 (cutter teeth at u = k p: a tooth space at theta 0) and gear 2 (cutter teeth shifted by
    p/2: a tooth at its contact point theta 2 = pi), in their body frames."""
    an = an or analyse(P)
    pp = an["pp"]
    g1 = generate_teeth(P, pp["C1"], pp["s1"], 0.0)
    g2 = generate_teeth(P, pp["C2full"], pp["s2full"], 0.5)
    return g1, g2

def rot(pts, ang, dx=0.0):
    c, s_ = math.cos(ang), math.sin(ang)
    return [(dx + x * c - y * s_, x * s_ + y * c) for x, y in pts]

def outline_radius(g, th):
    """Outline radius at body angle th by linear interpolation in the ray table (rays uniform from -pi)."""
    n = len(g)
    x = (math.remainder(th, 2 * math.pi) + math.pi) / (2 * math.pi) * n
    k = int(x) % n
    f = x - int(x)
    return g[k][1] + f * (g[(k + 1) % n][1] - g[k][1])

def mesh_check(P, an, g1, g2, n_pos=72):
    """Rotate the pair through one revolution of gear 1 (gear 1 by -phi1, gear 2 by +phi2). For the outline points of
    each gear near the contact point, transform them into the body frame of the other gear and compare their radius
    with the other outline radius at the same angle (exact for star-shaped outlines): gap = rho - R(theta) < 0 means
    interference. Returns the smallest radial gap (about 0 for conjugate flanks; resolution-limited)."""
    pp = an["pp"]
    a, m = pp["a"], P["m"]
    P1 = outline_xy(g1)
    P2 = outline_xy(g2)
    res = []
    N = len(pp["phi1"]) - 1
    for q in range(n_pos):
        i = q * N // n_pos
        f1, f2 = pp["phi1"][i], pp["phi2"][i]
        cx = pp["r1"][i]
        dmin = float("inf")
        for x, y in rot(P2, f2, a):                      # gear-2 points in world -> gear-1 body frame
            if (x - cx) ** 2 + y * y > (2.5 * m) ** 2:
                continue
            bx, by = rot([(x, y)], f1)[0]
            dmin = min(dmin, math.hypot(bx, by) - outline_radius(g1, math.atan2(by, bx)))
        for x, y in rot(P1, -f1):                        # gear-1 points in world -> gear-2 body frame
            if (x - cx) ** 2 + y * y > (2.5 * m) ** 2:
                continue
            bx, by = rot([(x - a, y)], -f2)[0]
            dmin = min(dmin, math.hypot(bx, by) - outline_radius(g2, math.atan2(by, bx)))
        res.append(dmin)
    return {"d_min": min(res), "d_per_pos": res}

# ---------------------------------------------------------------- chapter 5: kinematics and dynamics
def load_torque(P, phi2):
    w0, w1 = P["work_window"]
    d = math.degrees(phi2) % 360
    return P["T0"] + (P["T_work"] if w0 <= d <= w1 else 0.0)

def kinematics(P, an):
    """Constant input speed w1: w2 = w1 r1/r2, alpha2 = w1^2 d(r1/r2)/dphi1; input torque from the power balance
    T1 = (T_load + J2 alpha2) w2 / w1 (gear 1 inertia does not need torque at constant speed)."""
    pp = an["pp"]
    w1 = P["n_in"] * 2 * math.pi / 60
    N = len(pp["phi1"]) - 1
    rows = []
    for i in range(N):
        g = pp["r1"][i] / pp["r2"][i]
        gp = (pp["r1"][(i + 1) % N] / pp["r2"][(i + 1) % N] - pp["r1"][i - 1] / pp["r2"][i - 1]) / (2 * 2 * math.pi / N)
        w2 = w1 * g
        al2 = w1 * w1 * gp
        Tl = load_torque(P, pp["phi2"][i])
        T1 = (Tl + P["J2"] * al2) * g
        rows.append({"phi1": pp["phi1"][i], "phi2": pp["phi2"][i], "w2": w2, "n2": w2 * 60 / (2 * math.pi), "alpha2": al2, "T_load": Tl, "T1": T1,
                     "Ft": T1 / (pp["r1"][i] / 1000)})
    t_cycle = 60 / P["n_in"]
    work = [r for r in rows if P["work_window"][0] <= math.degrees(r["phi2"]) % 360 <= P["work_window"][1]]
    t_work = len(work) / len(rows) * t_cycle
    return {"rows": rows, "w1": w1, "n2_min": min(r["n2"] for r in rows), "n2_max": max(r["n2"] for r in rows),
            "alpha2_max": max(abs(r["alpha2"]) for r in rows), "T1_max": max(r["T1"] for r in rows), "T1_min": min(r["T1"] for r in rows),
            "T1_mean": sum(r["T1"] for r in rows) / len(rows), "Ft_max": max(abs(r["Ft"]) for r in rows), "t_work": t_work, "t_cycle": t_cycle,
            "work_share": t_work / t_cycle}

def simulate(P, an, J_fly=0.0, revs=4, steps_per_rev=720):
    """Time simulation with a real motor (linear slip line) and the variable inertia of the driven side. Lagrange with
    q = phi1, g(q) = dphi2/dphi1 = r1/r2:  (J1 + J_fly + J2 g^2) q'' + J2 g g' q'^2 = T_motor(q') - T_load g.
    RK4; returns the speed of gear 1 and gear 2 over the last revolution and the speed fluctuation."""
    pp = an["pp"]
    N = len(pp["phi1"]) - 1
    gt = [pp["r1"][i] / pp["r2"][i] for i in range(N)]
    def gfun(q):
        x = (q % (2 * math.pi)) / (2 * math.pi) * N
        i = int(x) % N
        f = x - int(x)
        g = gt[i] + f * (gt[(i + 1) % N] - gt[i])
        gp = (gt[(i + 1) % N] - gt[i]) / (2 * math.pi / N)
        ph2 = pp["phi2"][i] + f * (pp["phi2"][i + 1] - pp["phi2"][i])
        return g, gp, ph2
    mo = P["motor"]
    w0, wN = mo["n_0"] * math.pi / 30, mo["n_N"] * math.pi / 30
    Tm = lambda w: mo["T_N"] * (w0 - w) / (w0 - wN)
    J1 = P["J1"] + J_fly
    def f(y):
        q, w = y
        g, gp, ph2 = gfun(q)
        rev = int(q // (2 * math.pi))
        acc = (Tm(w) - load_torque(P, ph2 + rev * 2 * math.pi * pp["ratio_rev"]) * g - P["J2"] * g * gp * w * w) / (J1 + P["J2"] * g * g)
        return (w, acc)
    y = (0.0, wN)
    dt = (2 * math.pi / wN) / steps_per_rev
    hist = []
    t = 0.0
    while y[0] < revs * 2 * math.pi:
        k1 = f(y)
        k2 = f((y[0] + dt / 2 * k1[0], y[1] + dt / 2 * k1[1]))
        k3 = f((y[0] + dt / 2 * k2[0], y[1] + dt / 2 * k2[1]))
        k4 = f((y[0] + dt * k3[0], y[1] + dt * k3[1]))
        y = (y[0] + dt / 6 * (k1[0] + 2 * k2[0] + 2 * k3[0] + k4[0]), y[1] + dt / 6 * (k1[1] + 2 * k2[1] + 2 * k3[1] + k4[1]))
        t += dt
        if y[0] >= (revs - 1) * 2 * math.pi:
            g, gp, ph2 = gfun(y[0])
            hist.append((t, y[0], y[1], y[1] * g))
    w = [h[2] for h in hist]
    wm = sum(w) / len(w)
    return {"hist": hist, "n1_min": min(w) * 30 / math.pi, "n1_max": max(w) * 30 / math.pi, "n1_mean": wm * 30 / math.pi,
            "delta": (max(w) - min(w)) / wm, "J_fly": J_fly}

# ---------------------------------------------------------------- chapter 6: tooth load and stresses (equivalent spur gear)
def lewis_Y(zv):
    """Lewis form factor of a 20 deg full-depth tooth (fit to the classic table, check): Y = 0.484 - 2.87 / z."""
    return max(0.15, 0.484 - 2.87 / max(zv, 8))

def stresses(P, an, kin):
    """At every mesh position: F_t = T1 / r1; contact stress with the flank radii rho_i sin(alpha) at the pitch point
    (Hertz, line contact, both steels): sigma_H = sqrt(F_n E* / (pi b R)), E* = E / (2 (1 - nu^2)), 1/R = 1/R1 + 1/R2;
    root stress (Lewis on the equivalent spur gear z_v = 2 rho / m): sigma_F = F_t / (b m Y)."""
    pp = an["pp"]
    a = pp["a"]
    al = math.radians(P["alpha"])
    Es = P["E"] / (2 * (1 - P["nu"] ** 2))
    N = len(pp["phi1"]) - 1
    r1 = pp["r1f"]
    out = []
    for i, k in enumerate(kin["rows"]):
        t = pp["phi1"][i]
        rho1 = polar_props(r1, t)["rho"]
        # gear-2 radius of curvature from its pitch-curve point table (circle through three neighbouring points)
        j0, j1, j2 = (i - 2) % N, i, (i + 2) % N
        p0, p1, p2 = pp["C2"][j0], pp["C2"][j1], pp["C2"][j2]
        ax, ay, bx, by = p1[0] - p0[0], p1[1] - p0[1], p2[0] - p0[0], p2[1] - p0[1]
        cr = ax * by - ay * bx
        rho2 = abs(math.dist(p0, p1) * math.dist(p1, p2) * math.dist(p0, p2) / (2 * cr)) if cr else float("inf")
        R1, R2 = rho1 * math.sin(al), rho2 * math.sin(al)
        Rr = 1 / (1 / R1 + 1 / R2)
        Ft = abs(k["Ft"])
        Fn = Ft / math.cos(al)
        sH = math.sqrt(Fn * Es / (math.pi * P["b"] * Rr))
        zv1, zv2 = 2 * rho1 / P["m"], 2 * rho2 / P["m"]
        sF = Ft / (P["b"] * P["m"] * min(lewis_Y(zv1), lewis_Y(zv2)))
        out.append({"phi1": t, "Ft": Ft, "rho1": rho1, "rho2": rho2, "sigma_H": sH, "sigma_F": sF, "zv1": zv1, "zv2": zv2})
    sHm = max(o["sigma_H"] for o in out)
    sFm = max(o["sigma_F"] for o in out)
    return {"rows": out, "sigma_H_max": sHm, "sigma_F_max": sFm, "S_H": P["sigma_H_lim"] / sHm, "S_F": P["sigma_F_lim"] / sFm}

# ---------------------------------------------------------------- chapter 7: 3-D model and CAD output
def outline_xy(g):
    return [(R * math.cos(t), R * math.sin(t)) for t, R in g]

def stl_text(name, g, b, bore):
    """Extruded gear with a bore: quads between the bore circle and the outline at the same ray angles (the outline is
    star-shaped about the centre by construction), side walls of outline and bore. ASCII STL, mm."""
    rb = bore / 2
    n = len(g)
    O = outline_xy(g)
    I = [(rb * math.cos(t), rb * math.sin(t)) for t, _ in g]
    tri = []
    for k in range(n):
        k2 = (k + 1) % n
        o1, o2, i1, i2 = O[k], O[k2], I[k], I[k2]
        for z, up in ((0.0, False), (b, True)):          # bottom / top annulus
            A, B, C, D = (i1 + (z,)), (o1 + (z,)), (o2 + (z,)), (i2 + (z,))
            tri += [(A, C, B), (A, D, C)] if not up else [(A, B, C), (A, C, D)]
        tri += [((*o1, 0.0), (*o2, 0.0), (*o2, b)), ((*o1, 0.0), (*o2, b), (*o1, b))]      # outer wall
        tri += [((*i1, 0.0), (*i2, b), (*i2, 0.0)), ((*i1, 0.0), (*i1, b), (*i2, b))]      # bore wall
    L = ["solid %s" % name]
    for A, B, C in tri:
        ux, uy, uz = B[0] - A[0], B[1] - A[1], B[2] - A[2]
        vx, vy, vz = C[0] - A[0], C[1] - A[1], C[2] - A[2]
        nx, ny, nz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
        d = math.sqrt(nx * nx + ny * ny + nz * nz) or 1.0
        L.append("facet normal %.6e %.6e %.6e\n outer loop" % (nx / d, ny / d, nz / d))
        for v in (A, B, C):
            L.append("  vertex %.5f %.5f %.5f" % v)
        L.append(" endloop\nendfacet")
    L.append("endsolid %s" % name)
    return "\n".join(L) + "\n", len(tri)

def stl_volume(text):
    """Volume of a closed triangle mesh (divergence theorem) - checks that the STL solid is watertight and oriented."""
    V = 0.0
    vs = []
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("vertex"):
            vs.append(tuple(float(x) for x in line.split()[1:]))
            if len(vs) == 3:
                a, b, c = vs
                V += (a[0] * (b[1] * c[2] - b[2] * c[1]) - a[1] * (b[0] * c[2] - b[2] * c[0]) + a[2] * (b[0] * c[1] - b[1] * c[0])) / 6
                vs = []
    return V

def dxf_text(polys):
    """Minimal ASCII DXF (R12) with closed LWPOLYLINE-equivalent POLYLINE entities, one layer per gear."""
    L = ["0", "SECTION", "2", "ENTITIES"]
    for layer, pts, (dx, dy) in polys:
        L += ["0", "POLYLINE", "8", layer, "66", "1", "70", "1"]
        for x, y in pts:
            L += ["0", "VERTEX", "8", layer, "10", "%.5f" % (x + dx), "20", "%.5f" % (y + dy), "30", "0.0"]
        L += ["0", "SEQEND"]
    L += ["0", "ENDSEC", "0", "EOF"]
    return "\n".join(L) + "\n"

def svg_text(an, g1, g2, phi_idx=0, scale=2.0):
    pp = an["pp"]
    a = pp["a"]
    W1 = rot(outline_xy(g1), -pp["phi1"][phi_idx])
    W2 = rot(outline_xy(g2), pp["phi2"][phi_idx], a)
    allp = W1 + W2
    x0, x1 = min(p[0] for p in allp) - 5, max(p[0] for p in allp) + 5
    y0, y1 = min(p[1] for p in allp) - 5, max(p[1] for p in allp) + 5
    pts = lambda W: " ".join("%.2f,%.2f" % ((x - x0) * scale, (y1 - y) * scale) for x, y in W)
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="%.0f" height="%.0f"><polygon points="%s" fill="#cfe0f7" stroke="#2a6fdb"/>'
            '<polygon points="%s" fill="#f7d6d6" stroke="#d03b3b"/></svg>\n') % ((x1 - x0) * scale, (y1 - y0) * scale, pts(W1), pts(W2))

# ---------------------------------------------------------------- summary / report / run
def summary(P, with_teeth=True):
    an = analyse(P)
    kin = kinematics(P, an)
    st = stresses(P, an, kin)
    sim = simulate(P, an)
    S = {"an": an, "kin": kin, "st": st, "sim": sim}
    if with_teeth:
        g1, g2 = gear_outlines(P, an)
        S.update(g1=g1, g2=g2, mesh=mesh_check(P, an, g1, g2))
    return S

def report_text(P, S=None):
    S = S or summary(P)
    an, kin, st, sim = S["an"], S["kin"], S["st"], S["sim"]
    pp = an["pp"]
    yn = lambda b: "OK" if b else "NOT OK"
    L = ["# Non-circular gear report - %s\n" % P["name"],
         "type %s, e %.3f, lobes %d / %d; module %.2f mm, z1 %d, alpha %.0f deg, face width %.0f mm" % (P["type"], P["e"], P["n1"], P["n2"], P["m"], P["z1"], P["alpha"], P["b"]),
         "\n## Pitch curves",
         "- size parameter %.3f mm, centre distance a %.3f mm, perimeters %.3f / %.3f mm (z1 %d, z2 %.2f %s), gear 2 turns %.3f rev per rev of gear 1" % (
             an["A"], an["a"], pp["L1"], pp["L2full"], P["z1"], an["z2"], "OK" if abs(an["z2"] - round(an["z2"])) < 0.01 else "NOT a whole number - change z1",
             pp["phi2"][-1] / (2 * math.pi)),
         "- pitch radius gear 1 %.2f ... %.2f mm; transmission ratio i = w1/w2 %.3f ... %.3f (variation %.2f : 1)" % (
             min(pp["r1"]), max(pp["r1"]), an["i_min"], an["i_max"], an["i_max"] / an["i_min"]),
         "- pressure-angle deviation up to %.1f deg -> working pressure angle %.1f ... %.1f deg" % (an["delta_max"], P["alpha"] - an["delta_max"], P["alpha"] + an["delta_max"]),
         "- smallest radius of curvature %.2f / %.2f mm, convex %s / %s; equivalent tooth number z_v min %.1f (undercut limit %.1f) -> %s" % (
             an["rho1_min"], an["rho2_min"], an["convex1"], an["convex2"], an["zv_min"], an["z_undercut"], yn(an["zv_min"] >= an["z_undercut"])),
         "\n## Kinematics at %.0f rpm input (constant)" % P["n_in"],
         "- gear 2 speed %.1f ... %.1f rpm, max angular acceleration %.1f rad/s2; working window %.0f ... %.0f deg of gear 2 takes %.3f s of %.3f s (%.0f %% of the cycle)" % (
             kin["n2_min"], kin["n2_max"], kin["alpha2_max"], P["work_window"][0], P["work_window"][1], kin["t_work"], kin["t_cycle"], 100 * kin["work_share"]),
         "- input torque %.1f ... %.1f N m (mean %.2f N m), tangential tooth force up to %.0f N" % (kin["T1_min"], kin["T1_max"], kin["T1_mean"], kin["Ft_max"]),
         "\n## Dynamics with the motor (slip line %.0f -> %.0f rpm, T_N %.0f N m), no flywheel" % (P["motor"]["n_0"], P["motor"]["n_N"], P["motor"]["T_N"]),
         "- input speed %.2f ... %.2f rpm (mean %.2f), speed fluctuation %.3f" % (sim["n1_min"], sim["n1_max"], sim["n1_mean"], sim["delta"]),
         "\n## Stresses (equivalent spur gear, check)",
         "- contact stress max %.0f MPa (S_H %.2f), root stress max %.0f MPa (S_F %.2f)" % (st["sigma_H_max"], st["S_H"], st["sigma_F_max"], st["S_F"])]
    if "mesh" in S:
        L += ["\n## Generated teeth and mesh check",
              "- %d rays per gear, %d rack positions per tooth; smallest signed distance between the flanks over one revolution %.3f mm (%s; resolution about %.3f mm)" % (
                  P["n_rays"], P["steps_per_tooth"], S["mesh"]["d_min"], "no interference" if S["mesh"]["d_min"] > -0.05 * P["m"] else "INTERFERENCE",
                  2 * math.pi * max(pp["r1"]) / P["n_rays"])]
    return "\n".join(L)

def run(P, out):
    os.makedirs(out, exist_ok=True)
    S = summary(P)
    rep = report_text(P, S)
    with open(os.path.join(out, "report.md"), "w", encoding="utf-8") as f:
        f.write(rep)
    an, g1, g2 = S["an"], S["g1"], S["g2"]
    a = an["pp"]["a"]
    files = []
    for name, g in (("gear1", g1), ("gear2", g2)):
        txt, nt = stl_text(name, g, P["b"], P["bore"])
        with open(os.path.join(out, name + ".stl"), "w", encoding="utf-8") as f:
            f.write(txt)
        with open(os.path.join(out, name + "_xyz.txt"), "w", encoding="utf-8") as f:     # SOLIDWORKS: Insert > Curve > Curve Through XYZ Points
            for x, y in outline_xy(g) + outline_xy(g)[:1]:
                f.write("%.5f %.5f 0\n" % (x, y))
        files += [name + ".stl", name + "_xyz.txt"]
    with open(os.path.join(out, "pair.dxf"), "w", encoding="utf-8") as f:
        f.write(dxf_text([("GEAR1", outline_xy(g1), (0.0, 0.0)), ("GEAR2", outline_xy(g2), (a, 0.0))]))
    with open(os.path.join(out, "pair.svg"), "w", encoding="utf-8") as f:
        f.write(svg_text(an, g1, g2))
    with open(os.path.join(out, "pitch_table.csv"), "w", encoding="utf-8") as f:
        f.write("phi1 deg,phi2 deg,r1 mm,r2 mm,i = w1/w2\n")
        pp = an["pp"]
        for i in range(0, len(pp["phi1"]), 4):
            f.write("%.3f,%.4f,%.4f,%.4f,%.5f\n" % (math.degrees(pp["phi1"][i]), math.degrees(pp["phi2"][i]), pp["r1"][i], pp["r2"][i], pp["r2"][i] / pp["r1"][i]))
    files += ["pair.dxf", "pair.svg", "pitch_table.csv"]
    print(rep)
    print("written: report.md, %s -> %s" % (", ".join(files), out))


