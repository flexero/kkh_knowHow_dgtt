def cmd_selftest():
    ok = []
    def chk(name, cond, info=""):
        ok.append(bool(cond))
        print("%-66s %s %s" % (name, "OK  " if cond else "FAIL", info))
    P = dict(DEFAULT)
    r1 = r1_fun(P, 60.0)
    a = centre_distance(r1, 1.0)
    chk("identical focal-pivot ellipses: closure gives a = 2 A (major axis)", abs(a - 120.0) < 1e-6, "%.6f" % a)
    chk("ellipse ratio range (1 - e)/(1 + e) ... (1 + e)/(1 - e)", abs(max(r1(t) / (a - r1(t)) for t in [math.pi * i / 180 for i in range(361)]) - 1.3 / 0.7) < 1e-9)
    pp = pitch_pair(P, 60.0)
    chk("pure rolling: arc lengths of both pitch curves are equal", abs(pp["L1"] - pp["L2"]) / pp["L1"] < 1e-5, "%.4f / %.4f" % (pp["L1"], pp["L2"]))
    Lr = math.pi * (3 * (60 + 60 * math.sqrt(1 - 0.09)) - math.sqrt((3 * 60 + 60 * math.sqrt(0.91)) * (60 + 3 * 60 * math.sqrt(0.91))))
    chk("perimeter = Ramanujan's ellipse perimeter", abs(pp["L1"] / Lr - 1) < 1e-5, "%.4f mm" % Lr)
    circ = dict(P, type="nlobe", e=0.0, n1=1, n2=2)
    pc = pitch_pair(circ, 50.0)
    chk("circles, gear 2 turning 1/2 rev: a = 3 r1 (ratio 2 spur pair)", abs(pc["a"] - 150.0) < 1e-6)
    fun = dict(P, type="function")
    pf = pitch_pair(fun, 120.0)
    phi2_exact = 2 * math.pi + 2 * 0.25 * 0           # integral of 1 + 0.25 sin over a revolution = 2 pi
    chk("function type: phi2(2 pi) = 2 pi (closure built in)", abs(pf["phi2"][-1] - phi2_exact) < 1e-6)
    k = polar_props(lambda t: 50.0, 0.3)["kappa"]
    chk("curvature of a circle = 1 / r", abs(k - 1 / 50.0) < 1e-6)
    # rack generation on a circle reproduces a standard involute spur gear: tooth thickness at the pitch circle = p/2
    Pc = dict(P, type="nlobe", e=0.0, n1=1, n2=1, m=4.0, z1=30, n_rays=2880)
    an = analyse(Pc, 60.0)
    g = generate_teeth(Pc, an["pp"]["C1"], an["pp"]["s1"], 0.0, 2880, 60)
    Rs = [R for _, R in g]
    chk("generated circle gear: tip radius r + m, root radius r - 1.25 m", abs(max(Rs) - 64.0) < 0.05 and abs(min(Rs) - 55.0) < 0.05, "%.3f / %.3f" % (max(Rs), min(Rs)))
    on = [R >= 60.0 for R in Rs]
    share = sum(on) / len(on)
    chk("generated circle gear: tooth occupies half the pitch circle (s = p/2)", abs(share - 0.5) < 0.01, "%.3f" % share)
    txt, nt = stl_text("t", g, 10.0, 20.0)
    Ve = stl_volume(txt)
    from_poly = 0.5 * sum(Rs[i] * Rs[(i + 1) % len(Rs)] * math.sin(2 * math.pi / len(Rs)) for i in range(len(Rs))) * 10 - math.pi * 10 ** 2 * 10 * (math.sin(2 * math.pi / len(Rs)) * len(Rs) / (2 * math.pi))
    chk("STL solid is closed and outward oriented: volume = area x width", abs(Ve / from_poly - 1) < 1e-6, "%.0f mm3" % Ve)
    an = analyse(P)
    g1, g2 = gear_outlines(P, an)
    good = mesh_check(P, an, g1, g2)["d_min"]
    bad = mesh_check(P, an, g1, generate_teeth(P, an["pp"]["C2full"], an["pp"]["s2full"], 0.0))["d_min"]
    chk("mesh check: generated ellipse pair is conjugate, wrong tooth phase collides", good > -0.05 * P["m"] and bad < -1.0, "%.3f / %.2f mm" % (good, bad))
    print("SELFTEST", "PASS" if all(ok) else "FAIL")
    return 0 if all(ok) else 1

def main(argv):
    if len(argv) < 2 or argv[1] in ("-h", "--help"):
        print(__doc__)
        return 0
    cmd = argv[1]
    if cmd == "params":
        print(json.dumps(DEFAULT, indent=2))
    elif cmd == "examples":
        cmd_examples()
    elif cmd in ("ch24", "ch56", "ch78") and ("demo_" + cmd) in globals():
        globals()["demo_" + cmd]()
    elif cmd == "selftest":
        return cmd_selftest()
    elif cmd == "run":
        P = dict(DEFAULT)
        out = "ncgear_out"
        if "--in" in argv:
            with open(argv[argv.index("--in") + 1], encoding="utf-8") as f:
                P.update(json.load(f))
        if "--out" in argv:
            out = argv[argv.index("--out") + 1]
        run(P, out)
    else:
        print("unknown command; see --help")
        return 2
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv))
