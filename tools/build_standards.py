"""Build the offline standards library for the Standards tab (web/std_data.js) from docs/16_standards_register.md.

Python standard library only (offline). Run again whenever guide 16 changes:

    python tools/build_standards.py            -> writes web/std_data.js
    python tools/build_standards.py --missing  -> also lists numbers cited in docs 31+ / web data that are not in guide 16

Source tables:
  * guide 16 §16 master table (one row per standard / family / law, grouped LAW, SAF, ROB, ...)
  * guide 16 §4 detailed register (project-specific requirements) – merged into the matching master row
Hand-written explainers and rows for newer guides live in web/std_extra.js (not generated).
"""
import io
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "16_standards_register.md")
OUT = os.path.join(ROOT, "web", "std_data.js")

BUY = []
LINK = re.compile(r"\[([^\]]+)\]\([^)]+\)")


def clean(t):
    t = LINK.sub(r"\1", t)
    t = t.replace("**", "").replace("`", "").replace("ⁿ", "").replace("<br>", " ")
    return re.sub(r"\s+", " ", t).strip()


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def key_of(name):
    """normalised base key, e.g. 'ISO 230-2:2014 (series)' -> 'ISO 230'"""
    n = clean(name).upper().replace("DIN EN ", "EN ").replace("BS EN ", "EN ").replace("EN ISO/IEC ", "ISO/IEC ").replace("EN ISO ", "ISO ")
    n = re.sub(r"^EN (6\d{4})", lambda m: "IEC " + m.group(1), n)   # EN 60204 = IEC 60204 (European adoption)
    m = re.match(r"((?:ISO/IEC|ISO/ASTM|ISO/TS|ISO/TR|IEC/TS|IEC/TR|ISO|IEC|EN|DIN SPEC|DIN|VDI/VDE|VDI|VDE|VDA|VDMA|ANSI/[A-Z]+|ANSI|ASME|NFPA|UL|ASTM|SAE AMS|SAE|AMS|API|DNV-ST|NASA-STD|MSFC-SPEC|OPC|IEEE|ISA|CIA|FEM|AGMA|IATF|DGUV|TRGS|EEMUA|NAMUR NE|BS)\s*[A-Z]?\s*[\d.]+)", n)
    if m:
        return re.sub(r"\s+", " ", m.group(1)).strip()
    m = re.match(r"(\d{4}/\d+/E[UC]+|\(EU\) \d{4}/\d+|\d{2,4}/\d+/EEC)", n)
    return m.group(1) if m else n[:40]


def parse():
    src = io.open(SRC, encoding="utf-8").read().split("\n")
    rows, detail, group, gname, sec = [], {}, "", "", ""
    for i, line in enumerate(src):
        if line.startswith("## "):
            sec = line[3:].strip()
        g = re.match(r"#### ([A-Z]+) – (.+)", line)
        if g:
            group, gname = g.group(1), g.group(2).strip()
            continue
        if not line.startswith("| ") or line.startswith("|---"):
            continue
        c = cells(line)
        if sec.startswith("16.") and len(c) >= 8 and c[0].isdigit():
            rows.append({"n": int(c[0]), "id": clean(c[1]), "ed": clean(c[2]), "title": clean(c[3]), "req": clean(c[4]),
                         "used": clean(c[5]), "bind": clean(c[6]), "status": clean(c[7]), "g": group, "gn": gname,
                         "newrow": "ⁿ" in c[1]})
        elif sec.startswith("21.") and len(c) == 6 and c[0] not in ("Pos.",):
            BUY.append({"pos": clean(c[0]), "doc": clean(c[1]), "ed": clean(c[2]), "why": clean(c[3]), "prio": clean(c[4]), "price": clean(c[5])})
        elif sec.startswith("4.") and len(c) == 6 and c[0] not in ("Standard",):
            detail[key_of(c[0])] = {"official": clean(c[1]), "covers": clean(c[2]), "project": clean(c[3]), "get": clean(c[5])}
    for r in rows:
        d = detail.get(key_of(r["id"]))
        if d:
            r.update(d)
        r["k"] = key_of(r["id"])
    return rows


def missing(rows):
    keys = {r["k"] for r in rows}
    pat = re.compile(r"\b((?:ISO/ASTM|ISO/IEC|ISO|IEC|EN|ASTM|SAE AMS|AMS|API|DNV-ST|NASA-STD|MSFC-SPEC|VDI|DIN SPEC|OPC)\s?[A-Z]?\s?\d{2,6}(?:-\d+)?)")
    found = {}
    files = [os.path.join(ROOT, "docs", f) for f in os.listdir(os.path.join(ROOT, "docs")) if re.match(r"(3\d|4\d)_", f)]
    files += [os.path.join(ROOT, "web", f) for f in ("mt_data.js", "amind_data.js", "amlpbf.js", "am.js")]
    for f in files:
        if not os.path.exists(f):
            continue
        for m in pat.finditer(io.open(f, encoding="utf-8").read()):
            k = key_of(m.group(1))
            if k not in keys and not re.match(r"(AMS [23]00|ENS )", k):   # AMS 200/300 = product names, not standards
                found.setdefault(k, set()).add(os.path.basename(f))
    return found


def main():
    rows = parse()
    groups = {}
    for r in rows:
        groups[r["g"]] = r["gn"]
    with io.open(OUT, "w", encoding="utf-8") as f:
        f.write("/* GENERATED by tools/build_standards.py from docs/16_standards_register.md – do not edit by hand. */\n")
        f.write("export const GROUPS = " + json.dumps(groups, ensure_ascii=False) + ";\n")
        f.write("export const BUY = " + json.dumps(BUY, ensure_ascii=False) + ";\n")
        f.write("export const ROWS = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"{len(rows)} rows, {len(groups)} groups, {sum(1 for r in rows if 'project' in r)} with project detail -> {OUT}")
    if "--missing" in sys.argv:
        for k, fs in sorted(missing(rows).items()):
            print(f"  missing: {k:28s} {', '.join(sorted(fs))}")


if __name__ == "__main__":
    main()
