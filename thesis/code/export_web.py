"""Export thesis results to web/phd_data.js for the "Doctoral research" tab (re-run after new experiments)."""
import collections
import csv
import json
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(HERE, '..', 'data')
OUT = os.path.join(HERE, '..', '..', 'web', 'phd_data.js')


def rampup(fn):
    rows = list(csv.DictReader(open(os.path.join(D, fn), encoding='utf-8')))
    by = collections.defaultdict(list)
    truth = collections.defaultdict(list)
    for r in rows:
        y = float(r['truth'])
        p, lo, hi = float(r['pred']), float(r['lo']), float(r['hi'])
        by[(r['method'], int(r['month']))].append((abs(p - y) / y, lo <= y <= hi, (hi - lo) / y, (p - y) / y))
        if r['method'] == 'B0':
            truth[int(r['month'])].append(y)
    methods = sorted({m for m, _ in by})
    out = {'months': list(range(1, 13)), 'truth': [round(statistics.mean(truth[k])) for k in range(1, 13)], 'methods': {}}
    for m in methods:
        mape = [round(100 * statistics.mean(e[0] for e in by[(m, k)]), 2) for k in range(1, 13)]
        allv = [e for k in range(2, 13) for e in by[(m, k)]]
        out['methods'][m] = {'mape': mape,
                             'mape_2_12': round(100 * statistics.mean(e[0] for e in allv), 2),
                             'coverage': round(100 * statistics.mean(e[1] for e in allv), 1),
                             'width': round(100 * statistics.mean(e[2] for e in allv), 2),
                             'bias': round(100 * statistics.mean(e[3] for e in allv), 2)}
    return out


def bottleneck():
    rows = list(csv.DictReader(open(os.path.join(D, 'bottleneck.csv'), encoding='utf-8')))
    out = {}
    for m in ('B0', 'P1', 'P07'):
        out[m] = {'hit': [round(100 * statistics.mean(int(r['hit']) for r in rows if r['method'] == m and int(r['month']) == k))
                          for k in range(1, 13)],
                  'cap': [round(100 * statistics.mean(float(r['cap_mape']) for r in rows if r['method'] == m and int(r['month']) == k), 1)
                          for k in range(1, 13)]}
    return out


def staging():
    import analyse_staging, staging as st
    out = {}
    for b in ('0.0', '0.5'):
        summ, pair, finals = analyse_staging.summary(os.path.join(D, f'staging_b{b}.csv'))
        out[b] = {'summary': {k: {kk: round(vv, 3) for kk, vv in v.items()} for k, v in summ.items()},
                  'pair': {k: [round(v[0], 3), round(v[1], 3), v[2], v[3]] for k, v in pair.items()},
                  'finals': {k: [[a, n] for a, n in v] for k, v in finals.items()}}
    eta = st.calibrate_eta()
    out['eta'] = {str(k): round(v, 4) for k, v in eta.items()}
    out['econ'] = {'hours': st.HOURS, 'stages': st.STAGES, 'months': st.MONTHS, 'margin': st.MARGIN, 'penalty': st.PENALTY,
                   'disc': st.DISC, 'terminal': st.TERMINAL, 'budget': st.BUDGET, 'opex': st.OPEX, 'demand': st.DEMAND}
    out['options'] = {k: [v[0], v[1], v[2]] for k, v in st.OPTIONS.items()}
    return out


def cases():
    c = json.load(open(os.path.join(D, 'case_study.json'), encoding='utf-8'))
    rows = c['case2_rampup']
    months = []
    for k in range(1, 13):
        rr = [r for r in rows if r['month'] == k]
        e = lambda m: round(100 * statistics.mean(abs(r[m] - r['truth']) / r['truth'] for r in rr), 1)
        months.append({'k': k, 'truth': round(statistics.mean(r['truth'] for r in rr)), 'B0': e('B0'), 'P07': e('P07'), 'P07D': e('P07D'),
                       'cov': round(100 * statistics.mean(r['P07D_lo'] <= r['truth'] <= r['P07D_hi'] for r in rr)),
                       'bn_twin': round(100 * statistics.mean(r['bn_twin'] == r['bn_true'] for r in rr)),
                       'bn_design': round(100 * statistics.mean(r['bn_design'] == r['bn_true'] for r in rr))})
    return {'P0': c['case1_P0'], 'sens': c['case1_sensitivity'], 'size1': c['case1_sizing'], 'table2': c['case2_table'],
            'cap2': c['case2_capacity'], 'des2': c['case2_des_mean'], 'ramp2': months, 'size2': c['case2_sizing'], 'size2_1s': c['case2_sizing_seq_1s']}


data = {
    'generated': 'thesis/code/export_web.py',
    'rampup': {w: rampup(f'rampup_w{w}.csv') for w in ('0.25', '1.0', '4.0')},
    'bottleneck': bottleneck(),
    'variance': [[1, 95.2, 122], [2, 43.9, 60], [4, 25.5, 48], [8, 25.7, 38], [12, 27.5, 38]],
    'comm': [json.loads(l) for l in open(os.path.join(D, 'comm_runs.jsonl'))],
    'http': json.load(open(os.path.join(D, 'http_bench.json'))),
    'staging': staging(),
    'cases': cases(),
}
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* GENERATED by thesis/code/export_web.py from thesis/data – do not edit by hand. [simulated] / [measured] thesis results. */\n')
    f.write('export const PHD = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print('written', OUT, os.path.getsize(OUT), 'bytes')
